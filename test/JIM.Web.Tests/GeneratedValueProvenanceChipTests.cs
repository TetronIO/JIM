using Bunit;
using JIM.Models.Logic;
using JIM.Models.Transactional;
using JIM.Web.Shared;
using Microsoft.AspNetCore.Components;
using Microsoft.AspNetCore.Components.Rendering;
using Microsoft.AspNetCore.Components.Web;
using MudBlazor;
using NUnit.Framework;

namespace JIM.Web.Tests;

/// <summary>
/// Covers the small provenance chip an attribute row wears when its committed value came from Unique Value
/// Generation (#242, Phase 3, Work Package D2, mockup screen 04): "Generated by JIM" versus "Adopted by JIM",
/// and its menu's "View history" link, which the caller can suppress.
/// </summary>
[TestFixture]
public class GeneratedValueProvenanceChipTests : JimComponentTestContext
{
    private static GeneratedValueAssignmentHeader BuildAssignment(bool adopted = false) => new()
    {
        AssignmentId = Guid.NewGuid(),
        AttributeName = "Account Name",
        Value = "joe.bloggs1",
        TokenKind = GeneratedValueTokenKind.OnlyIfTaken,
        SyncRuleId = 42,
        SyncRuleMappingId = 7,
        State = GeneratedValueAssignmentState.Committed,
        Adopted = adopted
    };


    [Test]
    public void GeneratedValueProvenanceChip_NotAdopted_RendersGeneratedByJim()
    {
        var cut = Render<GeneratedValueProvenanceChip>(p => p.Add(c => c.Assignment, BuildAssignment()));

        Assert.That(cut.Find("[data-testid='jim-generated-value-chip']").TextContent.Trim(), Is.EqualTo("Generated by JIM"));
    }

    [Test]
    public void GeneratedValueProvenanceChip_Adopted_RendersAdoptedByJim()
    {
        var cut = Render<GeneratedValueProvenanceChip>(p => p.Add(c => c.Assignment, BuildAssignment(adopted: true)));

        Assert.That(cut.Find("[data-testid='jim-generated-value-chip']").TextContent.Trim(), Is.EqualTo("Adopted by JIM"));
    }

    [Test]
    public async Task GeneratedValueProvenanceChip_ClickingTheChip_OpensTheMenu()
    {
        // The behaviour a real user exercises: clicking the chip itself, not the keyboard path the other tests
        // use for reliability. A custom MudMenu ActivatorContent is not wired to the menu automatically; it
        // must call MenuContext.ToggleAsync itself (see the chip's OnClick), and this is the test that would
        // have failed before that wiring was added (found via runtime verification: the menu never opened for
        // a real click in the browser, even though it opened in this test suite via the keyboard path below).
        var cut = Render(RenderWithPopoverProvider(BuildAssignment(), showHistoryLink: true));

        await cut.Find("[data-testid='jim-generated-value-chip']").ClickAsync(new MouseEventArgs());

        cut.WaitForAssertion(() =>
            Assert.That(cut.FindAll("[data-testid='jim-generated-value-chip-open-rule']"), Has.Count.EqualTo(1)));
    }

    [Test]
    public async Task GeneratedValueProvenanceChip_OpenSynchronisationRuleLink_PointsAtTheOwningRule()
    {
        var cut = Render(RenderWithPopoverProvider(BuildAssignment(), showHistoryLink: true));
        await OpenMenuAsync(cut);

        cut.WaitForAssertion(() =>
        {
            var link = cut.Find("[data-testid='jim-generated-value-chip-open-rule']");
            Assert.That(link.GetAttribute("href"), Does.EndWith("/admin/sync-rules/42"));
        });
    }

    [Test]
    public async Task GeneratedValueProvenanceChip_ShowHistoryLinkTrue_RendersViewHistory()
    {
        var cut = Render(RenderWithPopoverProvider(BuildAssignment(), showHistoryLink: true));
        await OpenMenuAsync(cut);

        cut.WaitForAssertion(() =>
            Assert.That(cut.FindAll("[data-testid='jim-generated-value-chip-view-history']"), Has.Count.EqualTo(1)));
    }

    [Test]
    public async Task GeneratedValueProvenanceChip_ShowHistoryLinkFalse_OmitsViewHistory()
    {
        var cut = Render(RenderWithPopoverProvider(BuildAssignment(), showHistoryLink: false));
        await OpenMenuAsync(cut);

        cut.WaitForAssertion(() =>
        {
            // The open-rule item always renders; waiting for it proves the menu has actually opened before
            // asserting the absence of the history item (otherwise "not found yet" and "correctly omitted"
            // are indistinguishable).
            Assert.That(cut.FindAll("[data-testid='jim-generated-value-chip-open-rule']"), Has.Count.EqualTo(1));
            Assert.That(cut.FindAll("[data-testid='jim-generated-value-chip-view-history']"), Is.Empty);
        });
    }

    /// <summary>
    /// The keyboard path (Enter on the focused activator) is MudMenu's own built-in accessibility handling,
    /// independent of a custom ActivatorContent's own click wiring; used here for the tests that only care
    /// about the menu's contents once open, to keep them independent of the click test above.
    /// </summary>
    private static Task OpenMenuAsync<T>(IRenderedComponent<T> cut) where T : IComponent =>
        cut.Find(".mud-menu-activator").KeyDownAsync(new KeyboardEventArgs { Key = "Enter", Code = "Enter" });

    /// <summary>
    /// MudMenu renders its content through MudPopoverProvider, which has no ChildContent/Body of its own, so it
    /// has to be rendered alongside the chip as a sibling rather than via RenderTree.Add (see TermHintTests).
    /// </summary>
    private static RenderFragment RenderWithPopoverProvider(GeneratedValueAssignmentHeader assignment, bool showHistoryLink)
    {
        return builder =>
        {
            builder.OpenComponent<MudPopoverProvider>(0);
            builder.CloseComponent();
            builder.OpenComponent<GeneratedValueProvenanceChip>(1);
            builder.AddComponentParameter(2, nameof(GeneratedValueProvenanceChip.Assignment), assignment);
            builder.AddComponentParameter(3, nameof(GeneratedValueProvenanceChip.ShowHistoryLink), showHistoryLink);
            builder.CloseComponent();
        };
    }
}
