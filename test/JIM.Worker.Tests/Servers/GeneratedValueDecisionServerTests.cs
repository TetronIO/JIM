    private void SeedEstate()
    {
        var accountName = new MetaverseAttribute { Id = 40, Name = "Account Name", Type = AttributeDataType.Text, AttributePlurality = AttributePlurality.SingleValued };
        var userType = new MetaverseObjectType { Id = 1, Name = "User", PluralName = "Users", Attributes = [accountName] };

        var hr = new ConnectedSystem { Id = HrSystemId, Name = "HR CSV" };
        var corporate = new ConnectedSystem { Id = CorporateAdId, Name = "Corporate AD" };
        var contractor = new ConnectedSystem { Id = ContractorLdapId, Name = "Contractor LDAP" };
        var ticketing = new ConnectedSystem { Id = TicketingId, Name = "Ticketing" };
        foreach (var system in new[] { hr, corporate, contractor, ticketing })
            _syncRepo.SeedConnectedSystem(system);

        var hrImport = new SyncRule
        {
            Id = HrImportRuleId, Name = "HR Import", Direction = SyncRuleDirection.Import, Enabled = true,
            ConnectedSystemId = HrSystemId, ConnectedSystem = hr, MetaverseObjectType = userType, MetaverseObjectTypeId = userType.Id
        };
        var accountNameMapping = new SyncRuleMapping
        {
            Id = AccountNameMappingId, SyncRule = hrImport, SyncRuleId = hrImport.Id, Enabled = true,
            TargetMetaverseAttribute = accountName, TargetMetaverseAttributeId = accountName.Id,
            Generation = new SyncRuleMappingGeneration { Id = AccountNameGenerationId, SyncRuleMappingId = AccountNameMappingId }
        };
        hrImport.AttributeFlowRules.Add(accountNameMapping);

        var corporateExport = ExportRule(CorporateAdExportRuleId, "Corporate AD Export", corporate, userType,
            Direct(accountName, new ConnectedSystemObjectTypeAttribute { Id = 200, Name = "sAMAccountName", Type = AttributeDataType.Text }));
        var contractorExport = ExportRule(ContractorExportRuleId, "Contractor Export", contractor, userType,
            Direct(accountName, new ConnectedSystemObjectTypeAttribute { Id = 300, Name = "uid", Type = AttributeDataType.Text }));

        var loginName = new ConnectedSystemObjectTypeAttribute { Id = 401, Name = "loginName", Type = AttributeDataType.Text };
        var loginNameMapping = new SyncRuleMapping
        {
            Id = LoginNameMappingId, Enabled = true, TargetConnectedSystemAttribute = loginName, TargetConnectedSystemAttributeId = loginName.Id,
            Generation = new SyncRuleMappingGeneration { Id = LoginNameGenerationId, SyncRuleMappingId = LoginNameMappingId },
            Sources = { new SyncRuleMappingSource { Order = 0, Expression = "Lower(mv[\"Account Name\"])" } }
        };
        var ticketingExport = ExportRule(TicketingExportRuleId, "Ticketing Export", ticketing, userType, loginNameMapping);

        foreach (var rule in new[] { hrImport, corporateExport, contractorExport, ticketingExport })
            _syncRepo.SeedSyncRule(rule);

        var now = DateTime.UtcNow;
        _rita = Person("Rita Okafor", userType);
        _sam = Person("Sam Adeyemi", userType);
        _lee = Person("Lee Chen", userType);
        _ana = Person("Ana Ruiz", userType);
        _joe = Person("Joe Bloggs", userType);
        _pat = Person("Pat Lee", userType);
