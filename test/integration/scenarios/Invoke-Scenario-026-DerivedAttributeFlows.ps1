}

function Get-Person {
    <#
    .SYNOPSIS
        One person's Metaverse Object header, found by Employee ID.
    #>
    param([Parameter(Mandatory=$true)][string]$EmployeeId)
    $person = @(Get-JIMMetaverseObject -AttributeName "Employee ID" -AttributeValue $EmployeeId -Attributes @(
        "Employee ID", "Account Name", "Email", "User Principal Name", "Training Status", "Training Summary")) | Select-Object -First 1
    Assert-NotNull -Value $person -Message "The Metaverse Object with Employee ID '$EmployeeId' exists"
    return $person
}

function Get-FirstValue {
    param($Entry, [Parameter(Mandatory=$true)][string]$Name)
    if ($null -eq $Entry -or -not $Entry.ContainsKey($Name)) { return $null }
    return @($Entry[$Name])[0]
}

function Get-DirectoryUserMap {
    <#
    .SYNOPSIS
        Every provisioned directory user under the user container, keyed by Employee ID: one search as
        the directory administrator rather than one per person.
    #>
    $entries = @(Find-DirectoryEntry -DirectoryConfig $DirectoryConfig -BaseDn $DirectoryConfig.UserContainer `
        -Filter "($employeeIdLdapAttr=*)" `
        -Attributes @($employeeIdLdapAttr, $DirectoryConfig.UserNameAttr, 'mail', 'userPrincipalName', 'physicalDeliveryOfficeName'))
    $map = @{}
    foreach ($entry in $entries) {
        $id = Get-FirstValue -Entry $entry -Name $employeeIdLdapAttr
        if ($id) { $map[$id] = $entry }
    }
    return $map
}

