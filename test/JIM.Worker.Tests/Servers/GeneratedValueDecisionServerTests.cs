    private MetaverseObject Person(string name, MetaverseObjectType type)
    {
        var mvo = new MetaverseObject { Id = Guid.NewGuid(), Type = type, CachedDisplayName = name };
        _syncRepo.SeedMetaverseObject(mvo);
        return mvo;
    }

    private GeneratedValueAssignment ImportValue(MetaverseObject mvo, MetaverseAttribute attribute, string value, Action<GeneratedValueAssignment> shape)
    {
        var assignment = new GeneratedValueAssignment
        {
            Id = Guid.NewGuid(), MetaverseObjectId = mvo.Id, MetaverseAttributeId = attribute.Id, Value = value, NormalisedValue = value.ToLowerInvariant(),
            SyncRuleMappingGenerationId = AccountNameGenerationId, State = GeneratedValueAssignmentState.Committed, CommittedAt = DateTime.UtcNow.AddDays(-30)
        };
        shape(assignment);
        _syncRepo.SeedGeneratedValueAssignment(assignment);
        return assignment;
    }

    private static void Hold(GeneratedValueAssignment assignment, DateTime since, int rejectedBy, GeneratedValueNeedsDecisionReason reason, int? anchoredBy)
    {
        assignment.State = GeneratedValueAssignmentState.NeedsDecision;
        assignment.NeedsDecisionEnteredAt = since;
        assignment.RejectedByConnectedSystemId = rejectedBy;
        assignment.AnchoredByConnectedSystemId = anchoredBy;
        assignment.NeedsDecisionReason = reason;
    }

    private static SyncRule ExportRule(int id, string name, ConnectedSystem system, MetaverseObjectType type, SyncRuleMapping mapping)
    {
        var rule = new SyncRule
        {
            Id = id, Name = name, Direction = SyncRuleDirection.Export, Enabled = true, ConnectedSystemId = system.Id, ConnectedSystem = system,
            MetaverseObjectType = type, MetaverseObjectTypeId = type.Id
        };
        mapping.SyncRule = rule;
        mapping.SyncRuleId = rule.Id;
        rule.AttributeFlowRules.Add(mapping);
        return rule;
    }

    private static SyncRuleMapping Direct(MetaverseAttribute source, ConnectedSystemObjectTypeAttribute target) => new()
    {
        Enabled = true,
        TargetConnectedSystemAttribute = target,
        TargetConnectedSystemAttributeId = target.Id,
        Sources = { new SyncRuleMappingSource { Order = 0, MetaverseAttributeId = source.Id, MetaverseAttribute = source } }
    };
