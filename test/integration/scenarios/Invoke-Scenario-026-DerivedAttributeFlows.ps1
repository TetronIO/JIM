function Add-HrCsvJoiner {
    <#
    .SYNOPSIS
        Appends one controlled row to hr-users.csv, matching whatever columns the file has (it carries no
        samAccountName, email or userPrincipalName: -OmitItOwnedAttributes).
    #>
    param(
        [Parameter(Mandatory=$true)][string]$EmployeeId,
        [Parameter(Mandatory=$true)][string]$FirstName,
        [Parameter(Mandatory=$true)][string]$LastName,
        [Parameter(Mandatory=$true)][string]$Department
    )

    $csv = @(Import-Csv $hrCsvPath)
    $columns = $csv[0].PSObject.Properties.Name
    $row = [ordered]@{}
    foreach ($col in $columns) {
        $row[$col] = switch ($col) {
            'employeeId'   { $EmployeeId }
            'firstName'    { $FirstName }
            'lastName'     { $LastName }
            'department'   { $Department }
            'title'        { 'Specialist' }
            'company'      { 'Panoply' }
            'displayName'  { "$FirstName $LastName" }
            'status'       { 'Active' }
            'employeeType' { 'Employee' }
            default        { '' }
        }
    }
    $csv += [PSCustomObject]$row
    $csv | Export-Csv -Path $hrCsvPath -NoTypeInformation -Encoding UTF8
    Copy-CsvToConnectorFiles -SourcePath $hrCsvPath
}

function Set-TrainingStatus {
    <#
    .SYNOPSIS
        Changes one person's trainingStatus in training-records.csv, or appends a training record for a
        person who has none (copying the shape of an existing row), and seeds the file into the volume.
    #>
    param(
        [Parameter(Mandatory=$true)][string]$EmployeeId,
        [Parameter(Mandatory=$true)][string]$Status
    )

    $rows = @(Import-Csv $trainingCsvPath)
    $existing = @($rows | Where-Object { $_.employeeId -eq $EmployeeId })
    if ($existing.Count -gt 0) {
        foreach ($row in $existing) { $row.trainingStatus = $Status }
    }
    else {
        $newRow = $rows[0] | Select-Object *
        $newRow.employeeId = $EmployeeId
        $newRow.trainingStatus = $Status
        if ($newRow.PSObject.Properties['samAccountName']) { $newRow.samAccountName = '' }
        $rows += $newRow
    }
    $rows | Export-Csv -Path $trainingCsvPath -NoTypeInformation -Encoding UTF8
    Copy-CsvToConnectorFiles -SourcePath $trainingCsvPath
}

