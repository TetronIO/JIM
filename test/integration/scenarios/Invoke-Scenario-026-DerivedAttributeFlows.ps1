function Invoke-RawJimApi {
    <#
    .SYNOPSIS
        A raw REST call against the JIM API, deliberately bypassing the JIM PowerShell module, so the
        REST half of a surface-parity assertion does not go through the module's own request building.
        Returns @{ StatusCode; Body; Message } and never throws on an HTTP error status.
    #>
    param(
        [Parameter(Mandatory=$true)][string]$Endpoint,
        [ValidateSet('GET', 'POST', 'PATCH', 'DELETE')][string]$Method = 'GET',
        [object]$Body
    )
    $params = @{
        Uri = "$($JIMUrl.TrimEnd('/'))$Endpoint"
        Method = $Method
        ContentType = 'application/json'
        Headers = @{ 'Accept' = 'application/json'; 'X-API-Key' = $ApiKey }
        SkipHttpErrorCheck = $true
        StatusCodeVariable = 'statusCode'
    }
    if ($Body) { $params.Body = $Body | ConvertTo-Json -Depth 10 }
    $response = Invoke-RestMethod @params
    $message = $null
    if ($response -and $response.PSObject.Properties['message']) { $message = $response.message }
    return @{ StatusCode = [int]$statusCode; Body = $response; Message = $message }
}

