<#
.SYNOPSIS
    Regenerates docs/hooks/diagram_metrics.json: the glyph widths the diagram renderer sizes text with.

.DESCRIPTION
    docs/hooks/diagrams.py turns each jim-diagram spec in a page into SVG at build time, and has to
    know how wide a label will be to size its box, wrap it, and fail the build when it cannot fit.
    Python has no font metrics without a new dependency, so the widths are measured once, here, in
    a real browser with the site's own webfonts (IBM Plex Sans and IBM Plex Mono, from the Google
    Fonts request docs/overrides/main.html makes), and committed.

    Each family and weight the renderer uses gets the advance width of every character it is likely
    to meet, in thousandths of an em, plus a default for anything else (the widest measured glyph,
    so an unknown character errs towards a box that is too big rather than one that overflows).

    Run it after changing the fonts the site loads, or the weights the renderer uses. It needs a
    browser (the one .devcontainer/setup.sh installs for the Playwright MCP server) and network
    access to fonts.googleapis.com.

.PARAMETER Check
    Measure again and compare with the committed file instead of writing it; exit non-zero when
    any width differs by more than 0.5 thousandths of an em.

.EXAMPLE
    pwsh -File ./scripts/Update-DiagramFontMetrics.ps1
#>
[CmdletBinding()]
param(
    [switch]$Check
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
$outPath = Join-Path $repoRoot 'docs/hooks/diagram_metrics.json'

. (Join-Path $PSScriptRoot 'JimPlaywright.ps1')
$playwrightModule = Resolve-PlaywrightModule

$driver = @'
const { chromium } = require(process.env.JIM_PW_MODULE);

// The faces the renderer sets text in (docs/hooks/diagrams.py, STYLES).
const FACES = [
  { family: 'sans', css: 'IBM Plex Sans', weights: [400, 600, 700] },
  { family: 'mono', css: 'IBM Plex Mono', weights: [400, 700] },
];
const CHARS = (() => {
  let s = '';
  for (let c = 32; c < 127; c++) s += String.fromCharCode(c);
  return s + '’‘“”–…·•é×→←';
})();

const html = `<!doctype html><html><head><meta charset="utf-8">
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;700&family=IBM+Plex+Sans:wght@400;600;700&display=block">
</head><body></body></html>`;

(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.setContent(html, { waitUntil: 'networkidle' });
  const result = await page.evaluate(async ({ faces, chars }) => {
    const out = {};
    const ctx = document.createElement('canvas').getContext('2d');
    for (const face of faces) {
      out[face.family] = {};
      for (const w of face.weights) {
        const font = `${w} 1000px "${face.css}"`;
        await document.fonts.load(font, chars);
        if (!document.fonts.check(font, 'A')) throw new Error(`${face.css} ${w} did not load`);
        ctx.font = font;
        const widths = {};
        let widest = 0;
        for (const ch of chars) {
          const v = Math.round(ctx.measureText(ch).width * 10) / 10;
          widths[ch] = v;
          if (v > widest) widest = v;
        }
        out[face.family][String(w)] = { default: widest, chars: widths };
      }
    }
    return out;
  }, { faces: FACES, chars: CHARS });
  await browser.close();
  process.stdout.write(JSON.stringify(result));
})().catch(err => { console.error((err && err.stack) || String(err)); process.exit(1); });
'@

$tempScript = Join-Path ([System.IO.Path]::GetTempPath()) ("jim-font-metrics-{0}.cjs" -f ([guid]::NewGuid().ToString('n')))
Set-Content -LiteralPath $tempScript -Value $driver -Encoding utf8
try {
    $env:JIM_PW_MODULE = $playwrightModule
    $json = & node $tempScript
    if ($LASTEXITCODE -ne 0) { throw "Measuring the diagram fonts failed (node exited $LASTEXITCODE)." }
}
finally {
    Remove-Item -LiteralPath $tempScript -Force -ErrorAction SilentlyContinue
    Remove-Item Env:JIM_PW_MODULE -ErrorAction SilentlyContinue
}

$measured = $json | ConvertFrom-Json -AsHashtable
$document = [ordered]@{
    '_comment' = 'Generated by scripts/Update-DiagramFontMetrics.ps1: advance widths in thousandths of an em. Do not edit by hand.'
    'sans'     = $measured['sans']
    'mono'     = $measured['mono']
}

if ($Check) {
    if (-not (Test-Path -LiteralPath $outPath)) { throw "Not found: $outPath. Run without -Check to create it." }
    $committed = Get-Content -LiteralPath $outPath -Raw | ConvertFrom-Json -AsHashtable
    $drift = [System.Collections.Generic.List[string]]::new()
    foreach ($family in 'sans', 'mono') {
        foreach ($weight in $measured[$family].Keys) {
            $now = $measured[$family][$weight]['chars']
            $then = $committed[$family][$weight]['chars']
            foreach ($ch in $now.Keys) {
                if (-not $then.ContainsKey($ch) -or [math]::Abs($now[$ch] - $then[$ch]) -gt 0.5) {
                    $drift.Add("$family $weight '$ch'")
                }
            }
        }
    }
    if ($drift.Count -gt 0) {
        Write-Host ("The committed diagram font metrics are out of date ({0} glyphs differ, e.g. {1})." -f $drift.Count, ($drift | Select-Object -First 5) -join ', ') -ForegroundColor Red
        Write-Host 'Run: pwsh -File ./scripts/Update-DiagramFontMetrics.ps1' -ForegroundColor Red
        exit 1
    }
    Write-Host 'The diagram font metrics are current.' -ForegroundColor Green
    exit 0
}

$document | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath $outPath -Encoding utf8NoBOM
Write-Host "Wrote $outPath" -ForegroundColor Green
