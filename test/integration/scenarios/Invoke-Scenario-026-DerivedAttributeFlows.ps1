<#
.SYNOPSIS
    Test Scenario 026: Metaverse-Derived Attribute Flows

.DESCRIPTION
    Exercises Metaverse-Derived Attribute Flows (#1750): import Attribute Flows whose expressions read
    mv["..."], evaluated by JIM in dependency order within one synchronisation, and re-evaluated by
    the hosting system's next synchronisation when an input changes in another system (the derived-input
    mark).

    The substrate is Scenario 001's, composed by Setup-Scenario-026.ps1 (Setup-Scenario-001.ps1
    -GenerateAccountName -DeriveFromAccountName), with the HR CSV generated by Get-OrGenerate-TestCSV.ps1
    -OmitItOwnedAttributes so the HR feed carries no samAccountName, email or userPrincipalName:

      Account Name         generated, Lower(firstName).Lower(lastName), OnlyIfTaken   step 1
      Email                mv["Account Name"] + "@panoply.local"                       step 2
      User Principal Name  mv["Email"]                                                 step 3
      Training Summary     "Training " + mv["Training Status"] (HR rule; Training Status
                           comes from the Training Records Source system), ContributeNoValue

    Email -> mail, User Principal Name -> userPrincipalName (Active Directory only; an RFC directory
    has no userPrincipalName) and Training Summary -> physicalDeliveryOfficeName are exported.

    Steps are CUMULATIVE: a named step runs everything up to and including itself.

      Ordering     Initial load. Every person's mail equals Account Name + "@panoply.local" and
                   userPrincipalName equals mail, in the Metaverse and the directory; two same-named
                   joiners carry the same suffix in all three. Training Summary is derived for everyone
                   with a training record (HR synchronised before Training, so it arrives through the
                   mark on the next HR Delta Synchronisation) and absent for everyone without one.
      Stability    A following Full Synchronisation stages no Pending Export and changes no derived value.
      CrossSystem  A Training CSV edit, Training Delta Synchronisation, then HR Delta Synchronisation
                   re-derives Training Summary and exports it. The Training synchronisation alone does
                   not: a derived flow runs only in its hosting system's synchronisation.
      WrongOrder   The same edit with HR synchronised first leaves Training Summary stale for one cycle;
                   the next HR Delta Synchronisation corrects it, because the Training synchronisation
                   marked the HR Connected System Object.
      MissingInput ContributeNoValue over an absent Training Status contributes nothing; once a training
                   record arrives the value follows on the next HR Delta Synchronisation.
      Cycle        A flow closing a dependency cycle across two Synchronisation Rules is refused with 400
                   naming both attributes and both rules, over raw REST and PowerShell alike.
      SurfaceParity Get-JIMSyncRuleMapping round-trips the derived expressions and their step facts,
                   matching raw REST; disabling the generated Account Name flow reports Email and (through
                   Email) User Principal Name as dependent derived flows.

.PARAMETER Step
    Which part to execute (cumulative).

.PARAMETER Template
    Data scale template. Small is the default and the feature's sign-off template.

.PARAMETER JIMUrl
    The URL of the JIM instance (default: http://localhost:5200)

.PARAMETER ApiKey
    API key for authentication

.PARAMETER ContinueOnError
    Continue executing remaining assertions even if one fails.

.PARAMETER SkipPopulate
    Accepted for runner compatibility. The target directory starts empty; JIM provisions every account.

.PARAMETER DirectoryConfig
    Directory configuration hashtable. Defaults to Get-DirectoryConfig -DirectoryType SambaAD.

.EXAMPLE
    ./Invoke-Scenario-026-DerivedAttributeFlows.ps1 -ApiKey "jim_..." -Template Small

.EXAMPLE
    ./Invoke-Scenario-026-DerivedAttributeFlows.ps1 -ApiKey "jim_..." -DirectoryConfig (Get-DirectoryConfig -DirectoryType OpenLDAP -Instance Primary)
#>

