function Get-HeaderValue {
    <#
    .SYNOPSIS
        One attribute off a Metaverse Object header (Get-JIMMetaverseObject -Attributes), $null when the
        object holds no value for it. Reads through PSObject.Properties because an absent attribute is
        an absent property, which strict mode refuses to read directly.
    #>
    param([Parameter(Mandatory=$true)]$Object, [Parameter(Mandatory=$true)][string]$Name)
    if ($null -eq $Object.attributes) { return $null }
    $property = $Object.attributes.PSObject.Properties[$Name]
    if ($property) { return $property.Value }
    return $null
}

function Get-Population {
    <#
    .SYNOPSIS
        Every User Metaverse Object with the attributes this scenario asserts on.
